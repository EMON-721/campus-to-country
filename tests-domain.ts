import assert from "node:assert/strict";
import {validate,monthEnd,focusedTotal,occurrences,typingResult} from "./lib/domain.ts";
import {wallToISO} from "./lib/time.ts";
assert.equal(monthEnd("2028-01-31",1),"2028-02-29");
assert.equal(monthEnd("2027-01-31",1),"2027-02-28");
assert.equal(monthEnd("2026-12-31",2),"2027-02-28");
assert.equal(wallToISO("2026-10-11","00:00","Asia/Dhaka"),"2026-10-10T18:00:00.000Z");
assert.throws(()=>wallToISO("2026-03-08","02:30","America/New_York"));
assert.equal(Date.parse(wallToISO("2026-03-09","00:00","America/New_York"))-Date.parse(wallToISO("2026-03-08","00:00","America/New_York")),23*3600000);
const study:any={id:"a",kind:"study",payload:{start:"2026-10-10T17:30:00Z",end:"2026-10-10T18:30:00Z",focusedMs:3600000,skill:"Reading",segments:[{start:"2026-10-10T17:30:00Z",end:"2026-10-10T18:30:00Z"}]}};
assert.equal(focusedTotal([study,study],"2026-10-11"),1800000);
assert.equal(focusedTotal([study],"2026-10-10"),1800000);
assert.doesNotThrow(()=>validate("study",study.payload));
assert.throws(()=>validate("study",{...study.payload,segments:[{start:"2026-10-10T17:30:00Z",end:"2026-10-10T18:00:00Z"},{start:"2026-10-10T17:50:00Z",end:"2026-10-10T18:20:00Z"}]}));
assert.throws(()=>validate("transaction",{account:"00000000-0000-4000-8000-000000000001",date:"2026-02-30",amount:10,direction:"credit",source:"Salary",description:""}));
assert.throws(()=>validate("transaction",{account:"00000000-0000-4000-8000-000000000001",date:"2026-02-28",amount:-10,direction:"credit",source:"Salary",description:""}));
const event:any={id:"b",kind:"event",payload:{start:"2026-01-31T12:00:00Z",end:"2026-01-31T13:00:00Z",recurrence:"monthly"}};
assert.deepEqual(occurrences(event,Date.parse("2026-01-01Z"),Date.parse("2026-04-01Z")).map(r=>r.payload.start.slice(0,10)),["2026-01-31","2026-02-28","2026-03-31"]);
assert.deepEqual(typingResult("abcde","abcXe",60000),{wpm:1,accuracy:80,errors:1});
assert.equal(typingResult("abc","",0).wpm,0);
console.log("15 domain assertions passed: dates, DST, midnight, deduplication, input validation, recurrence and typing.");
